const clickDelete = id => settings.webContents.executeJavaScript(`Array.from(document.querySelectorAll('.account-setting')).find(row => row.querySelector('input')?.getAttribute('aria-label') === ${JSON.stringify(accounts[1].name + '名称')}).querySelector('.delete-account').click()`);
await clickDelete(accounts[1].id);
await new Promise(r=>setTimeout(r,150));
assert.equal((await invoke('window.workspace.load()')).accounts.length, accounts.length);
assert.equal(fixtureDb.videoLibrary().find(v => v.videoPath === downloaded && v.projectName === '手动下载').accountId, accounts[1].id);
response = 1;
await clickDelete(accounts[1].id);
await new Promise(r=>setTimeout(r,400));
assert.equal((await invoke('window.workspace.load()')).accounts.some(a=>a.id===accounts[1].id),false);
assert.equal(fs.readFileSync(downloaded, 'utf8'), 'download fixture');
assert.equal(fixtureDb.task(task.id).accountId, null);
assert.equal(fixtureDb.task(task.id).videoPath, downloaded);
assert.ok(fixtureDb.videoLibrary().some(v => v.videoPath === downloaded && v.accountId === null && v.projectId === 0));
assert.ok(fixtureDb.videoLibrary().some(v => v.videoPath === otherDownload && v.accountId === accounts[0].id));
assert.deepEqual(fixtureDb.db.pragma('foreign_key_check'), []);
