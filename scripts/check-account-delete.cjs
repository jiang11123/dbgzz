assert.equal(await settings.webContents.executeJavaScript('document.querySelectorAll(".account-setting input[type=number]").length'), 0);
assert.equal(await settings.webContents.executeJavaScript('document.body.innerText.includes("秒/天") || document.body.innerText.includes("手动重置")'), false);
