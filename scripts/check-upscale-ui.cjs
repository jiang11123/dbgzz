const { app, BrowserWindow, ipcMain } = require('electron');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const testRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'doubao-upscale-ui-'));
app.setPath('userData', testRoot);
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 1480, height: 1080, webPreferences: { preload: path.join(root, 'dist/main/preload/preload.js'), sandbox: true, contextIsolation: true, backgroundThrottling: false, offscreen: true } });
  try {
    const { WorkspaceDatabase } = require('../dist/main/main/database');
    const { validateEligiblePaths } = require('../dist/main/main/video-upscale');
    const db = new WorkspaceDatabase();
    const fixtures = ['portrait.mp4', 'landscape.mp4'].map(p => path.join(root, 'exports/upscale-check', p));
    const third = path.join(testRoot, 'third.mp4'); fs.copyFileSync(fixtures[0], third); fixtures.push(third);
    fixtures.forEach(file => db.recordShareDownload(file, path.basename(file), 1));
    let loads = 0, requests = [], jobs = [];
    ipcMain.handle('workspace:load', () => { loads++; return { accounts: db.accounts(), projects: db.projects(), dashboard: db.dashboard(), downloadDirectory: testRoot }; });
    ipcMain.handle('videos:list', () => db.videoLibrary());
    ipcMain.handle('files:url', (_e, file) => require('node:url').pathToFileURL(file).toString());
    ipcMain.handle('upscale:list', () => jobs);
    ipcMain.handle('upscale:start', (_e, paths, target) => {
      requests.push({ paths: validateEligiblePaths(paths, db.videoLibrary().map(i => i.videoPath)), target });
      jobs = paths.map((inputPath, index) => ({ id: String(index), inputPath, target, state: 'queued', stage: '等待处理' }));
      return jobs;
    });
    const evaluate = code => win.webContents.executeJavaScript(code);
    const waitFor = async code => { for (let i = 0; i < 100; i++) { if (await evaluate(code)) return; await pause(50); } throw new Error('UI timeout: ' + code); };
    await win.loadFile(path.join(root, 'dist/renderer/index.html'));
    await waitFor(`document.querySelector('nav')`);
    await evaluate(`Array.from(document.querySelectorAll('nav button')).find(b=>b.textContent==='视频库').click()`);
    await waitFor(`document.querySelectorAll('.library-card').length === 3`);
    await evaluate(`document.querySelectorAll('.library-card input')[0].click(); document.querySelectorAll('.library-card input')[1].click()`);
    await waitFor(`document.querySelectorAll('.library-card input:checked').length === 2`);
    await evaluate(`document.querySelectorAll('.library-card')[0].dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,clientX:350,clientY:380}))`);
    await waitFor(`document.querySelector('[role=menu]')`);
    assert.ok((await evaluate(`document.querySelector('[role=menu]').textContent`)).includes('2 个视频'));
    await pause(600);
    fs.writeFileSync(path.join(root, 'exports/upscale-check/multi-select-menu.png'), (await win.webContents.capturePage()).toPNG());
    await evaluate(`document.querySelectorAll('[role=menuitem]')[0].click()`);
    await waitFor(`document.querySelectorAll('.upscale-job').length === 2`);
    assert.equal(requests[0].target, '2k'); assert.equal(requests[0].paths.length, 2);
    await evaluate(`document.querySelectorAll('.library-card')[2].dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,clientX:350,clientY:380}))`);
    await waitFor(`document.querySelectorAll('.library-card input:checked').length === 1`);
    await evaluate(`document.querySelectorAll('[role=menuitem]')[1].click()`);
    await pause(100);
    assert.equal(requests[1].target, '4k'); assert.equal(requests[1].paths.length, 1);
    await evaluate(`document.querySelector('[aria-label="全选视频"]').click()`);
    await waitFor(`document.querySelectorAll('.library-card input:checked').length === 3`);
    win.webContents.send('workspace:changed');
    await pause(250);
    assert.equal(await evaluate(`document.querySelectorAll('.library-card input:checked').length`), 3, 'refresh preserves selection');
    await evaluate(`document.querySelectorAll('.library-card-content')[0].click()`);
    await pause(50);
    await evaluate(`document.querySelectorAll('.library-card-content')[2].dispatchEvent(new MouseEvent('click',{bubbles:true,shiftKey:true}))`);
    await waitFor(`document.querySelectorAll('.library-card input:checked').length === 3`);
    const before = loads; await pause(350);
    assert.ok(loads - before < 3, 'workspace must not continuously reload on each data update');
    const result = { inputPath: fixtures[0], outputPath: fixtures[1], duration: 1 };
    db.recordUpscaleVideo(result.inputPath, result.outputPath);
    assert.ok(db.videoLibrary().some(item => item.projectName === '视频超分' && item.videoPath === result.outputPath));
    jobs = [{ id: 'live', inputPath: fixtures[0], target: '2k', state: 'running', stage: 'Video2X AI 超分（第 1 轮）', progress: { percent: 37.5, frame: 75, total: 200, fps: 2.5, elapsed: '00:00:30', remaining: '00:00:50' } }];
    win.webContents.send('upscale:changed');
    await waitFor(`document.querySelector('.upscale-notice')?.textContent.includes('37.5%')`);
    assert.equal(await evaluate(`Boolean(document.querySelector('.upscale-notice .download-location'))`), false);
    assert.equal(await evaluate(`document.querySelector('.upscale-notice progress').value`), 37.5);
    await pause(500);
    fs.writeFileSync(path.join(root, 'exports/upscale-check/live-progress.png'), (await win.webContents.capturePage()).toPNG());
    jobs[0] = { ...jobs[0], state: 'completed', stage: '已完成', outputPath: fixtures[1] };
    win.webContents.send('upscale:changed');
    await waitFor(`document.querySelector('.upscale-notice')?.textContent.includes('超分完成，视频已保存')`);
    assert.equal(await evaluate(`Boolean(document.querySelector('.upscale-notice .download-location'))`), true);
    console.log('PASS: real-time progress display; no download action before completion; final output action after completion');
    console.log('PASS: checkbox/Shift/all selection; 2K batch and 4K single context actions; refresh stability; SQLite result archive without duration tracking');
    app.exit(0);
  } catch (error) { console.error(error); app.exit(1); }
});
