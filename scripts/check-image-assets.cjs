const { app, BrowserWindow, dialog, nativeImage } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'doubao-assets-ui-'));
app.setPath('userData', profile);
process.env.CANVAS_BRIDGE_PORT = '0';
const source = path.join(profile, '共享参考.png');
fs.writeFileSync(source, nativeImage.createFromBitmap(Buffer.from([80, 160, 240, 255]), { width: 1, height: 1 }).toPNG());
const second = path.join(profile, '第二张.png');
fs.writeFileSync(second, nativeImage.createFromBitmap(Buffer.from([240, 120, 60, 255]), { width: 1, height: 1 }).toPNG());
let diskDialogs = 0;
dialog.showOpenDialog = async () => { diskDialogs++; return { canceled: false, filePaths: [source, second] }; };
let started = false;
const timeout = setTimeout(() => { console.error('Timed out'); app.exit(1); }, 45000);
require('../dist/main/main/main.js');
app.on('browser-window-created', (_event, main) => {
  if (started) return;
  started = true;
  main.webContents.once('did-finish-load', async () => {
    try {
      const invoke = code => main.webContents.executeJavaScript(code);
      await invoke('window.workspace.openImageAssets()');
      const panel = BrowserWindow.getAllWindows().find(w => w !== main);
      if (panel.webContents.isLoading()) await new Promise(resolve => panel.webContents.once('did-finish-load', resolve));
      const assets = await panel.webContents.executeJavaScript('window.workspace.importImageAssets()');
      assert.equal(assets.length, 2);
      await new Promise(resolve => setTimeout(resolve, 150));
      assert.equal(await invoke('document.querySelectorAll(".asset-bar-thumb").length'), 0);
      assert.deepEqual(await invoke('window.workspace.listQuickImages()'), []);
      await invoke('Array.from(document.querySelectorAll(".asset-bar-controls button")).find(b => b.textContent === "选择图片资产").click()');
      await new Promise(resolve => setTimeout(resolve, 200));
      await panel.webContents.executeJavaScript('document.querySelectorAll(".image-asset-card input").forEach(input => input.click())');
      await panel.webContents.executeJavaScript('Array.from(document.querySelectorAll("button")).find(b => b.textContent === "加入快捷预览").click()');
      await new Promise(resolve => setTimeout(resolve, 200));
      assert.equal(diskDialogs, 1);
      assert.equal(await invoke('document.querySelectorAll(".asset-bar-thumb").length'), 2);
      assert.equal(main.getBrowserViews()[0].getBounds().y, 134);
      let dragged;
      main.webContents.startDrag = item => { dragged = item; };
      await invoke(`window.workspace.dragImageAssets(${JSON.stringify(assets.map(a => a.id))})`);
      await new Promise(resolve => setTimeout(resolve, 100));
      assert.equal(dragged.files.length, 2);
      assert.ok(fs.existsSync(dragged.files[0]));
      assert.equal(dragged.icon.isEmpty(), false);
      fs.unlinkSync(source);
      const accounts = await invoke('window.workspace.load().then(d => d.accounts)');
      for (const account of accounts.slice(0, 2)) {
        await invoke(`window.workspace.openAccount(${account.id})`);
        const view = main.getBrowserViews()[0];
        await view.webContents.loadURL('data:text/html,<input type="file" accept="image/*" multiple><script>window.changes=0;document.querySelector("input").onchange=()=>window.changes++</script>');
        await invoke('Array.from(document.querySelectorAll(".asset-bar-controls button")).find(b => b.textContent === "全选").click()');
        await invoke('Array.from(document.querySelectorAll(".asset-bar-controls button")).find(b => b.textContent === "批量导入").click()');
        await new Promise(resolve => setTimeout(resolve, 300));
        await invoke('Array.from(document.querySelectorAll(".asset-bar-controls button")).find(b => b.textContent === "取消选择").click()');
        assert.deepEqual(await view.webContents.executeJavaScript('({length:document.querySelector("input").files.length,changes:window.changes})'), { length: 2, changes: 1 });
      }
      await assert.rejects(panel.webContents.executeJavaScript(`window.workspace.useImageAssets(${JSON.stringify([assets[0].id])}, ${accounts[0].id})`));
      await panel.webContents.reload();
      await new Promise(resolve => panel.webContents.once('did-finish-load', resolve));
      const state = await panel.webContents.executeJavaScript(`new Promise(resolve => { const timer=setInterval(() => { const img=document.querySelector('.image-asset-card img'); if(img?.complete && img.naturalWidth){clearInterval(timer);resolve({cards:document.querySelectorAll('.image-asset-card').length,text:document.body.innerText});}},50); })`);
      assert.equal(state.cards, 2);
      assert.ok(state.text.includes(accounts[1].name));
      await invoke('Array.from(document.querySelectorAll(".asset-bar-controls button")).find(b => b.textContent === "全选").click()');
      await invoke('Array.from(document.querySelectorAll(".asset-bar-controls button")).find(b => b.textContent === "移出快捷预览").click()');
      await new Promise(resolve => setTimeout(resolve, 200));
      assert.equal(await invoke('document.querySelectorAll(".asset-bar-thumb").length'), 0);
      assert.equal((await invoke('window.workspace.listImageAssets()')).items.length, 2);
      await panel.webContents.executeJavaScript('Array.from(document.querySelectorAll("button")).find(b => b.textContent === "全选").click()');
      await panel.webContents.executeJavaScript('Array.from(document.querySelectorAll("button")).find(b => b.textContent === "加入快捷预览").click()');
      await new Promise(resolve => setTimeout(resolve, 200));
      assert.equal(await invoke('document.querySelectorAll(".asset-bar-thumb").length'), 2);
      assert.equal(diskDialogs, 1);
      const shot = await panel.webContents.capturePage();
      fs.mkdirSync(path.join(__dirname, '../exports'), { recursive: true });
      fs.writeFileSync(path.join(__dirname, '../exports/image-assets-check.png'), shot.toPNG());
      fs.writeFileSync(path.join(__dirname, '../exports/image-assets-bar-check.png'), (await main.webContents.capturePage()).toPNG());
      console.log('PASS: choose library assets from toolbar/panel without disk dialog, remove shortcuts preserves assets, select all, two-account batch upload, native drag payload');
      clearTimeout(timeout); app.quit();
    } catch (error) { console.error(error); app.exit(1); }
  });
});
